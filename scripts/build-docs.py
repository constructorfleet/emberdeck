for name, text in pages.items():
    # The sources are trusted repository documents, never job or plugin output.
    if name in source_paths:
        text = re.sub(r'\]\(([^)\s]+)\)', lambda match: rewrite_link(match, source_paths[name]), text)
    body = markdown.markdown(text, extensions=['fenced_code', 'tables', 'toc'])
    nav = make_nav(name)
    html = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>EmberDeck | ' + escape(name) + '</title><style>' + style + '</style>' + nav + '<main id="main-content" tabindex="-1">' + body + '<footer>Documentation for v' + escape(version) + ' · <a href="https://github.com/constructorfleet/emberdeck/tree/' + revision + '">Release source</a> · <a href="LICENSE.txt">AGPL-3.0</a></footer></main></html>'
    (out / (name + '.html')).write_text(html, encoding='utf-8')
shutil.copy('LICENSE', out / 'LICENSE.txt')
shutil.copy('THIRD_PARTY_NOTICES.txt', out / 'THIRD_PARTY_NOTICES.txt')

assets = Path('docs/assets')
if assets.exists():
    shutil.copytree(assets, out / 'assets')

# Broken internal links and screenshot references fail CI instead of reaching the release site.
from html.parser import HTMLParser
class LinkChecker(HTMLParser):
    def handle_starttag(self, tag, attrs):
        if tag not in ('a', 'img'):
            return
        values = dict(attrs)
        if tag == 'img' and not values.get('alt', '').strip():
            raise SystemExit(f'Documentation screenshot needs alt text in {self.page}')
        href = values.get('src' if tag == 'img' else 'href', '')
        if not href or href.startswith(('#', 'https://', 'http://', 'mailto:')):
            return
        target = href.split('#', 1)[0]
        if not (out / target).is_file():
            raise SystemExit(f'Broken documentation link in {self.page}: {href}')
checker = LinkChecker()
for path in out.glob('*.html'):
    checker.page = path.name
    checker.feed(path.read_text(encoding='utf-8'))
