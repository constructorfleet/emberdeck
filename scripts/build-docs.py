"""Render release docs, with API route index and CLI help derived from source/build."""
from pathlib import Path
from html import escape
import os
import re
import shutil
import subprocess
import markdown

out = Path('dist/docs')
if out.exists():
    shutil.rmtree(out)
out.mkdir(parents=True, exist_ok=True)
sources = [Path('README.md'), Path('CONTRIBUTING.md'), *sorted(Path('docs').glob('*.md'))]
pages = {('index' if p.name == 'README.md' else p.stem): p.read_text() for p in sources}
routes = set()
for path in Path('internal/server').glob('*.go'):
    if not path.name.endswith('_test.go'):
        routes.update(re.findall(r'\.HandleFunc\("([A-Z]+ [^"\n]+)"', path.read_text()))
pages['api-routes'] = '# API route index\n\nGenerated from the registered server routes in this release. All API routes require bearer authentication.\n\n' + '\n'.join('- `' + route + '`' for route in sorted(routes)) + '\n\nSee [API contracts](api.html) for request shapes and state transitions.\n'
exe = Path('bin/emberdeck' + ('.exe' if os.name == 'nt' else '')).resolve()
help_text = []
for command in ['serve', 'driver']:
    result = subprocess.run([str(exe), command, '-h'], text=True, capture_output=True, check=True)
    help_text.append('## ' + command + '\n\n```text\n' + result.stdout + result.stderr + '```\n')
pages['cli'] = '# CLI reference\n\nGenerated by the executable built from this release.\n\n' + '\n'.join(help_text)
version = Path('version.txt').read_text().strip()
nav = '<nav><a class="brand" href="index.html">EmberDeck</a><span>v' + escape(version) + '</span>' + ''.join('<a href="' + name + '.html">' + escape(name.replace('-', ' ').title()) + '</a>' for name in pages) + '</nav>'
style = '''body{margin:0;background:#10161e;color:#dae3ec;font:16px/1.65 system-ui}nav{display:flex;flex-wrap:wrap;gap:1rem;padding:1rem 4vw;background:#1a2532;align-items:center}a{color:#ffb171}nav .brand{font-weight:800;font-size:1.3rem}main{max-width:86ch;margin:3rem auto;padding:0 1.5rem}pre{overflow:auto;background:#1a2532;padding:1.2rem;border-radius:8px}code{font-size:.9em}table{border-collapse:collapse;width:100%}td,th{padding:.6rem;border:1px solid #435264;text-align:left}h1,h2,h3{line-height:1.25;color:#fff}footer{margin:3rem 0;border-top:1px solid #435264;padding-top:1rem}'''
for name, text in pages.items():
    # The sources are trusted repository documents, never job or plugin output.
    text = re.sub(r'\]\((?:docs/)?([A-Za-z0-9_-]+)\.md(#[^)]*)?\)', lambda m: '](' + ('index' if m[1] == 'README' else m[1]) + '.html' + (m[2] or '') + ')', text)
    body = markdown.markdown(text, extensions=['fenced_code', 'tables', 'toc'])
    html = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>EmberDeck | ' + escape(name) + '</title><style>' + style + '</style>' + nav + '<main>' + body + '<footer>Documentation for v' + escape(version) + ' · <a href="https://github.com/ConstructorFleet/emberdeck">Release source</a> · <a href="LICENSE.txt">AGPL-3.0</a></footer></main></html>'
    (out / (name + '.html')).write_text(html, encoding='utf-8')
shutil.copy('LICENSE', out / 'LICENSE.txt')

# Broken internal links fail CI instead of reaching the release site.
from html.parser import HTMLParser
class LinkChecker(HTMLParser):
    def handle_starttag(self, tag, attrs):
        if tag != 'a':
            return
        href = dict(attrs).get('href', '')
        if not href or href.startswith(('#', 'https://', 'http://', 'mailto:')):
            return
        target = href.split('#', 1)[0]
        if not (out / target).is_file():
            raise SystemExit(f'Broken documentation link in {self.page}: {href}')
checker = LinkChecker()
for path in out.glob('*.html'):
    checker.page = path.name
    checker.feed(path.read_text(encoding='utf-8'))
