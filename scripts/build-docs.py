"""Render release docs, with API route index and CLI help derived from source/build."""
from pathlib import Path
from html import escape
import os
import re
import shutil
import subprocess
import markdown
from urllib.parse import urlsplit, unquote

out = Path('dist/docs')
if out.exists():
    shutil.rmtree(out)
out.mkdir(parents=True, exist_ok=True)
sources = [Path('README.md'), Path('CONTRIBUTING.md'), *sorted(Path('docs').rglob('*.md'))]
pages, source_paths = {}, {}
for path in sources:
    name = 'index' if path.name == 'README.md' else path.stem
    if name in pages:
        raise SystemExit(f'Documentation page names must be unique: {path}')
    pages[name] = path.read_text(encoding='utf-8')
    source_paths[name] = path
page_targets = {path.resolve(): name + '.html' for name, path in source_paths.items()}
repo_root = Path.cwd().resolve()
assets_root = (repo_root / 'docs/assets').resolve()
revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip()
source_url = 'https://github.com/constructorfleet/emberdeck/blob/' + revision + '/'

def rewrite_link(match, source):
    href = match[1]
    parsed = urlsplit(href)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return match[0]
    target = (source.parent / unquote(parsed.path)).resolve()
    fragment = '#' + parsed.fragment if parsed.fragment else ''
    if target in page_targets:
        return '](' + page_targets[target] + fragment + ')'
    if target == repo_root / 'LICENSE':
        return '](LICENSE.txt' + fragment + ')'
    try:
        relative = target.relative_to(assets_root)
        return '](assets/' + relative.as_posix() + fragment + ')'
    except ValueError:
        pass
    if target.is_file():
        try:
            return '](' + source_url + target.relative_to(repo_root).as_posix() + fragment + ')'
        except ValueError:
            pass
    return match[0]

routes = set()
for path in Path('internal/server').glob('*.go'):
    if not path.name.endswith('_test.go'):
        routes.update(re.findall(r'\.HandleFunc\("([A-Z]+ [^"\n]+)"', path.read_text()))
pages['api-routes'] = '# API route index\n\nGenerated from the registered server routes in this release. All API routes require bearer authentication.\n\n' + '\n'.join('- `' + route + '`' for route in sorted(routes)) + '\n\nSee [API contracts](api.html) for request shapes and state transitions.\n'
exe = Path('bin/emberdeck' + ('.exe' if os.name == 'nt' else '')).resolve()
help_text = []
for command in ['serve', 'driver']:
    result = subprocess.run([str(exe), command, '-h'], text=True, capture_output=True, check=True)
    help_text.append('## ' + command + '\n\n```text\n' + result.stdout + result.stderr + '```\n')
pages['cli'] = '# CLI reference\n\nGenerated by the executable built from this release. Use `emberdeck -version` to print its version.\n\n' + '\n'.join(help_text)
version = Path('version.txt').read_text().strip()
nav = '<nav><a class="brand" href="index.html">EmberDeck</a><span>v' + escape(version) + '</span>' + ''.join('<a href="' + name + '.html">' + escape(name.replace('-', ' ').title()) + '</a>' for name in pages) + '</nav>'
style = '''body{margin:0;background:#10161e;color:#dae3ec;font:16px/1.65 system-ui}nav{display:flex;flex-wrap:wrap;gap:1rem;padding:1rem 4vw;background:#1a2532;align-items:center}a{color:#ffb171}nav .brand{font-weight:800;font-size:1.3rem}main{max-width:86ch;margin:3rem auto;padding:0 1.5rem;overflow-wrap:anywhere}pre{overflow:auto;background:#1a2532;padding:1.2rem;border-radius:8px}code{font-size:.9em;overflow-wrap:anywhere}img{display:block;max-width:100%;height:auto;border:1px solid #435264;border-radius:8px;margin:1.2rem 0}table{border-collapse:collapse;width:100%}td,th{padding:.6rem;border:1px solid #435264;text-align:left}h1,h2,h3{line-height:1.25;color:#fff}footer{margin:3rem 0;border-top:1px solid #435264;padding-top:1rem}'''
for name, text in pages.items():
    # The sources are trusted repository documents, never job or plugin output.
    if name in source_paths:
        text = re.sub(r'\]\(([^)\s]+)\)', lambda match: rewrite_link(match, source_paths[name]), text)
    body = markdown.markdown(text, extensions=['fenced_code', 'tables', 'toc'])
    html = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>EmberDeck | ' + escape(name) + '</title><style>' + style + '</style>' + nav + '<main>' + body + '<footer>Documentation for v' + escape(version) + ' · <a href="https://github.com/constructorfleet/emberdeck/tree/' + revision + '">Release source</a> · <a href="LICENSE.txt">AGPL-3.0</a></footer></main></html>'
    (out / (name + '.html')).write_text(html, encoding='utf-8')
shutil.copy('LICENSE', out / 'LICENSE.txt')
shutil.copy('THIRD_PARTY_NOTICES.txt', out / 'THIRD_PARTY_NOTICES.txt')

assets = Path('docs/assets')
if assets.exists():
    shutil.copytree(assets, out / 'assets')

# Broken internal links and screenshot references fail CI instead of reaching the release site.
from html.parser import HTMLParser
class LinkChecker(HTMLParser):
    def handle_starttag(self, tag, attrs):
        if tag not in ('a', 'img'):
            return
        values = dict(attrs)
        if tag == 'img' and not values.get('alt', '').strip():
            raise SystemExit(f'Documentation screenshot needs alt text in {self.page}')
        href = values.get('src' if tag == 'img' else 'href', '')
        if not href or href.startswith(('#', 'https://', 'http://', 'mailto:')):
            return
        target = href.split('#', 1)[0]
        if not (out / target).is_file():
            raise SystemExit(f'Broken documentation link in {self.page}: {href}')
checker = LinkChecker()
for path in out.glob('*.html'):
    checker.page = path.name
    checker.feed(path.read_text(encoding='utf-8'))
